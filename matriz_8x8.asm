; ============================================================
; ATmega328P + MAX7219 + matriz 8x8
;
; Arduino Uno
;
; CLK = D13 = PB5
; DIN = D11 = PB3
; CS  = D10 = PB2
;
; Animação:
; Um único LED percorre a matriz inteira em "cobrinha".
;
; Linha 1:  esquerda -> direita
; Linha 2:  direita  -> esquerda
; Linha 3:  esquerda -> direita
; Linha 4:  direita  -> esquerda
; ...
;
; Os 64 padrões ficam na Flash.
; Z aponta para a posição atual da tabela.
; ============================================================


; ============================================================
; REGISTRADORES DO ATMEGA328P
; ============================================================

.equ PINB,  0x03
.equ DDRB,  0x04
.equ PORTB, 0x05


; ============================================================
; PINOS
; ============================================================

.equ CLK, 5       ; PB5 = Arduino D13
.equ DIN, 3       ; PB3 = Arduino D11
.equ CS,  2       ; PB2 = Arduino D10


; ============================================================
; STACK POINTER
; ============================================================

.equ SPL, 0x3D
.equ SPH, 0x3E


; ============================================================
; QUANTIDADE DE MAX7219
; ============================================================

.equ NUM_DEV, 1


; ============================================================
; PROGRAMA
; ============================================================

.section .text

.org 0x0000

    rjmp reset


; ============================================================
; RESET / INICIALIZAÇÃO
; ============================================================

reset:

    ; --------------------------------------------------------
    ; Inicializa Stack Pointer
    ;
    ; SP = 0x08FF
    ;
    ; SPH = parte alta
    ; SPL = parte baixa
    ; --------------------------------------------------------

    ldi r16, 0x08
    out SPH, r16

    ldi r16, 0xFF
    out SPL, r16


    ; --------------------------------------------------------
    ; Configura os pinos como saída
    ; --------------------------------------------------------

    sbi DDRB, CLK
    sbi DDRB, DIN
    sbi DDRB, CS


    ; --------------------------------------------------------
    ; Estado inicial dos pinos
    ; --------------------------------------------------------

    cbi PORTB, CLK
    cbi PORTB, DIN
    sbi PORTB, CS


    ; --------------------------------------------------------
    ; Aguarda o MAX7219 estabilizar
    ; --------------------------------------------------------

    rcall delay


    ; ========================================================
    ; CONFIGURAÇÃO DO MAX7219
    ; ========================================================


    ; --------------------------------------------------------
    ; Display Test OFF
    ;
    ; 0x0F = Display-Test
    ; 0x00 = funcionamento normal
    ; --------------------------------------------------------

    ldi r18, 0x0F
    ldi r19, 0x00

    rcall send_command


    ; --------------------------------------------------------
    ; Shutdown ON
    ;
    ; 0x0C = Shutdown
    ; 0x00 = desligado
    ;
    ; Configuramos o MAX7219 enquanto o display está desligado.
    ; --------------------------------------------------------

    ldi r18, 0x0C
    ldi r19, 0x00

    rcall send_command


    ; --------------------------------------------------------
    ; Decode Mode
    ;
    ; 0x09 = Decode Mode
    ; 0x00 = sem decode
    ; --------------------------------------------------------

    ldi r18, 0x09
    ldi r19, 0x00

    rcall send_command


    ; --------------------------------------------------------
    ; Intensidade
    ;
    ; 0x0A = intensidade
    ; 0x00 = intensidade mínima
    ; --------------------------------------------------------

    ldi r18, 0x0A
    ldi r19, 0x00

    rcall send_command


    ; --------------------------------------------------------
    ; Scan Limit
    ;
    ; 0x0B = Scan Limit
    ; 0x07 = oito linhas
    ; --------------------------------------------------------

    ldi r18, 0x0B
    ldi r19, 0x07

    rcall send_command


    ; ========================================================
    ; APAGA AS 8 LINHAS
    ; ========================================================

    ldi r24, 0x01


apagar:

    ; Registro da linha
    mov r18, r24

    ; Dados = 0
    ldi r19, 0x00

    rcall send_command


    ; Próxima linha
    inc r24


    ; Chegou na linha 9?
    cpi r24, 9

    brne apagar


    ; ========================================================
    ; SAI DO SHUTDOWN
    ; ========================================================

    ldi r18, 0x0C
    ldi r19, 0x01

    rcall send_command


    ; ========================================================
    ; INICIALIZA A TABELA DA COBRINHA
    ; ========================================================

    ; --------------------------------------------------------
    ; Z = endereço inicial da tabela
    ;
    ; Z = ZH:ZL
    ; --------------------------------------------------------

    ldi ZL, lo8(cobrinha)
    ldi ZH, hi8(cobrinha)


    ; --------------------------------------------------------
    ; r24 = linha atual
    ;
    ; começa na linha 1
    ; --------------------------------------------------------

    ldi r24, 0x01


    ; --------------------------------------------------------
    ; r26 = posição dentro da linha
    ;
    ; começa em 0
    ; --------------------------------------------------------

    clr r26


; ============================================================
; LOOP PRINCIPAL
; ============================================================

inicio:


    ; --------------------------------------------------------
    ; Lê o próximo byte da tabela
    ;
    ; r23 = Flash[Z]
    ;
    ; depois:
    ;
    ; Z = Z + 1
    ; --------------------------------------------------------

    lpm r23, Z+


    ; --------------------------------------------------------
    ; Envia:
    ;
    ; r18 = número da linha
    ; r19 = padrão dos LEDs
    ; --------------------------------------------------------

    mov r18, r24
    mov r19, r23

    rcall send_command


    ; --------------------------------------------------------
    ; Mantém o LED aceso por um tempo
    ; --------------------------------------------------------

    rcall delay


    ; --------------------------------------------------------
    ; Apaga a linha atual
    ; --------------------------------------------------------

    mov r18, r24
    ldi r19, 0x00

    rcall send_command


    ; ========================================================
    ; PRÓXIMA POSIÇÃO
    ; ========================================================

    inc r26


    ; --------------------------------------------------------
    ; Já percorreu 8 posições?
    ;
    ; r26:
    ;
    ; 0
    ; 1
    ; 2
    ; ...
    ; 7
    ;
    ; depois vira 8
    ; --------------------------------------------------------

    cpi r26, 8

    brne inicio


    ; ========================================================
    ; TERMINOU UMA LINHA
    ; ========================================================

    ; Reinicia posição dentro da linha
    clr r26


    ; Próxima linha
    inc r24


    ; --------------------------------------------------------
    ; Já terminou as 8 linhas?
    ;
    ; Quando r24 = 9, terminou.
    ; --------------------------------------------------------

    cpi r24, 9

    brne inicio


    ; ========================================================
    ; TERMINOU OS 64 LEDs
    ; ========================================================

    ; --------------------------------------------------------
    ; MUITO IMPORTANTE:
    ;
    ; Z volta para o começo da tabela.
    ;
    ; Assim ele nunca continua lendo memória depois
    ; dos 64 bytes de "cobrinha".
    ; --------------------------------------------------------

    ldi ZL, lo8(cobrinha)
    ldi ZH, hi8(cobrinha)


    ; Volta para linha 1
    ldi r24, 0x01


    ; Volta para posição 0
    clr r26


    ; Começa novamente
    rjmp inicio



; ============================================================
; SEND_COMMAND
;
; Entrada:
;
; r18 = endereço do registrador MAX7219
; r19 = valor do registrador
;
; Exemplo:
;
; r18 = 0x01
; r19 = 0b00000100
;
; significa:
;
; linha 1 = 00000100
;
; ============================================================

send_command:

    ; --------------------------------------------------------
    ; CS = LOW
    ;
    ; começa uma transmissão
    ; --------------------------------------------------------

    cbi PORTB, CS


    ; --------------------------------------------------------
    ; Quantidade de MAX7219
    ; --------------------------------------------------------

    ldi r25, NUM_DEV


send_cmd_loop:


    ; --------------------------------------------------------
    ; Envia endereço do registrador
    ; --------------------------------------------------------

    mov r16, r18

    rcall send_byte


    ; --------------------------------------------------------
    ; Envia dados
    ; --------------------------------------------------------

    mov r16, r19

    rcall send_byte


    ; Próximo dispositivo
    dec r25

    brne send_cmd_loop


    ; --------------------------------------------------------
    ; CS = HIGH
    ;
    ; MAX7219 aplica os dados
    ; --------------------------------------------------------

    sbi PORTB, CS


    ret



; ============================================================
; SEND_BYTE
;
; Entrada:
;
; r16 = byte que será enviado
;
; Envia primeiro o bit mais significativo.
;
; ============================================================

send_byte:

    ; contador = 8 bits
    ldi r17, 8


send_loop:


    ; --------------------------------------------------------
    ; Desloca r16 para esquerda
    ;
    ; O bit 7 vai para Carry.
    ;
    ; Exemplo:
    ;
    ; r16 = 10000000
    ;
    ; depois LSL:
    ;
    ; Carry = 1
    ; r16   = 00000000
    ; --------------------------------------------------------

    lsl r16


    ; --------------------------------------------------------
    ; Se Carry = 1
    ; envia HIGH
    ; --------------------------------------------------------

    brcs bit_one


    ; --------------------------------------------------------
    ; Carry = 0
    ; envia LOW
    ; --------------------------------------------------------

    cbi PORTB, DIN

    rjmp clock


bit_one:

    ; Carry = 1
    ; envia HIGH

    sbi PORTB, DIN


clock:

    ; --------------------------------------------------------
    ; Pequeno atraso antes do clock
    ;
    ; Esses NOPs são importantes no seu módulo MAX7219.
    ; --------------------------------------------------------

    nop
    nop


    ; CLK HIGH

    sbi PORTB, CLK


    ; Mantém HIGH por alguns ciclos

    nop
    nop
    nop
    nop


    ; CLK LOW

    cbi PORTB, CLK


    ; Pequeno espaço antes do próximo bit

    nop
    nop


    ; --------------------------------------------------------
    ; Próximo bit
    ; --------------------------------------------------------

    dec r17

    brne send_loop


    ret



; ============================================================
; DELAY
;
; Usa:
;
; r20
; r21
; r22
;
; IMPORTANTE:
;
; Não usar r22 como contador da animação,
; porque esta rotina destrói o conteúdo de r22.
; ============================================================

delay:

    ldi r20, 20


delay_outer:

    ldi r21, 255


delay_middle:

    ldi r22, 255


delay_inner:

    dec r22

    brne delay_inner


    dec r21

    brne delay_middle


    dec r20

    brne delay_outer


    ret



; ============================================================
; TABELA DA COBRINHA
;
; 8 LINHAS × 8 POSIÇÕES
;
; TOTAL = 64 BYTES
;
; Cada byte representa uma posição do LED.
;
; ============================================================

cobrinha:


    ; ========================================================
    ; LINHA 1
    ;
    ; esquerda -> direita
    ; ========================================================

    .byte 0b00000001
    .byte 0b00000010
    .byte 0b00000100
    .byte 0b00001000
    .byte 0b00010000
    .byte 0b00100000
    .byte 0b01000000
    .byte 0b10000000


    ; ========================================================
